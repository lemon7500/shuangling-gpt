test('settings usage selector ignores an older response and never rebinds the task', async () => {
  const html = await readFile(new URL('../../src/settings/index.html', import.meta.url), 'utf8');
  const script = html.match(/<script>([\s\S]*?)<\/script>/)[1];
  const nodes = new Map();
  const node = id => { if (!nodes.has(id)) nodes.set(id, { value: '', textContent: '', hidden: false, classList: { toggle() {} }, replaceChildren(...children) { this.children = children; }, scrollIntoView() {} }); return nodes.get(id); };
  const choices = [{ threadId: 'old-chat', threadName: '修复面板', projectName: '旧项目' }, { threadId: 'new-chat', threadName: '优化清晰度', projectName: '新项目' }, { threadId: 'duplicate-a', threadName: '同名任务', projectName: '同一项目' }, { threadId: 'duplicate-b', threadName: '同名任务', projectName: '同一项目' }, { threadId: 'unnamed', threadName: null, projectName: '新项目' }];
  const snapshot = (threadId, count) => ({ selection: { status: 'available', source: 'selected-chat', ...choices.find(choice => choice.threadId === threadId), choices }, project: { status: 'available', scope: 'project', usedTokens: count, observedAt: new Date(at).toISOString() }, context: { status: 'unknown' }, account: { weekly: { status: 'available', remainingPercent: threadId === 'old-chat' ? 11 : 22 } } });
  let value = snapshot('old-chat', 111), holdNext = false, failChat = false, failAccount = false, release;
  const writes = [];
  let accountRequests = 0;
  const response = data => ({ ok: true, json: async () => data });
  const context = vm.createContext({ document: { getElementById: node, createElement: () => ({}) }, location: { hash: '#test', search: '' }, URLSearchParams, setInterval() {}, fetch: async (url, options) => {
    if (options.method === 'POST') { const body = JSON.parse(options.body); writes.push({ url, body }); value = snapshot(body.threadId, body.threadId === 'new-chat' ? 222 : 111); return response({ ok: true }); }
    if (url.endsWith('/account-usage')) { accountRequests++; if (failAccount) throw Error('account-source-unavailable'); return response({ fiveHour: { status: 'not-applicable' }, weekly: { status: 'available', remainingPercent: 93 } }); }
    if (url.endsWith('/usage')) { if (failChat) throw Error('chat-source-unavailable'); const sampled = value; if (holdNext) { holdNext = false; return new Promise(resolve => { release = () => resolve(response(sampled)); }); } return response(sampled); }
    return response(url.endsWith('/threads') ? { threads: [] } : url.endsWith('/appearance') ? { size: 396, position: { corner: 'bottom-right', marginX: 20, marginY: 12 } } : { status: { state: 'working', threadId: 'bound-chat' }, control: {} });
  } });
  await vm.runInContext(script, context);
  assert.equal(node('usageThread').children[1].textContent, '修复面板 · 旧项目');
  assert.equal(node('usageThread').children[2].title, '优化清晰度\n新项目\nnew-chat');
  assert.equal(node('usageThread').children[3].textContent, '同名任务 · 同一项目 · duplicate-a');
  assert.equal(node('usageThread').children[4].textContent, '同名任务 · 同一项目 · duplicate-b');
  assert.equal(node('usageThread').children[5].textContent, '未命名聊天 · 新项目 · unnamed');
  const originalOptions = node('usageThread').children;
  context.document.activeElement = node('usageThread');
  node('usageThread').value = 'new-chat';
  await vm.runInContext('usage()', context);
  assert.equal(node('usageThread').value, 'new-chat', 'polling must not reset a focused select');
  assert.equal(node('usageThread').children, originalOptions, 'polling must not rebuild the focused select');
  context.document.activeElement = null;
  holdNext = true;
  const oldRequest = vm.runInContext('usage()', context);
  node('usageThread').value = 'new-chat';
  await node('usageThread').onchange();
  assert.equal(node('projectValue').textContent, '222 tokens');
  assert.equal(node('weeklyValue').textContent, '剩余 93%', 'neither chat response replaces the independent account quota');
  assert.equal(node('fiveHourCard').hidden, true);
  assert.equal(accountRequests, 1, 'selecting a chat does not refresh or clear account quota');
  release(); await oldRequest;
  assert.equal(node('projectValue').textContent, '222 tokens');
  assert.equal(node('usageSource').textContent, '所选聊天 · 优化清晰度 · 新项目');
  assert.equal(node('bound').textContent, '整个 Codex');
  assert.equal(node('bound').title, 'bound-chat');
  assert.deepEqual(writes, [{ url: '/api/usage-target', body: { threadId: 'new-chat' } }]);
  value = { ...value, selection: { status: 'unknown', threadId: 'new-chat', threadName: '过期身份', choices: [] } };
  await vm.runInContext('usage()', context);
  assert.equal(node('usageThread').hidden, false, 'an HTTP 200 unknown snapshot keeps the safe chat list');
  assert.equal(node('usageThread').children[1].textContent, '修复面板 · 旧项目');
  assert.equal(node('usageSource').title, '');
  assert.equal(node('usageSource').textContent, '用量来源未知');
  assert.equal(node('projectValue').textContent, '未知');
  assert.equal(node('weeklyValue').textContent, '剩余 93%');
  node('usageThread').value = 'old-chat';
  await node('usageThread').onchange();
  assert.deepEqual(writes.at(-1), { url: '/api/usage-target', body: { threadId: 'old-chat' } });
  assert.equal(node('projectValue').textContent, '111 tokens', 'a different chat remains selectable after an unknown snapshot');
  failChat = true;
  await vm.runInContext('usage()', context);
  assert.match(node('contextValue').textContent, /未知/);
  assert.equal(node('weeklyValue').textContent, '剩余 93%', 'chat failures do not clear the shared quota');
  assert.equal(node('usageThread').hidden, false, 'a failed chat read keeps the escape route to other chats');
  assert.equal(node('usageThread').children[1].textContent, '修复面板 · 旧项目');
  assert.equal(node('usageThread').children[2].textContent, '优化清晰度 · 新项目');
  assert.equal(node('usageThread').value, '', 'cached choices do not preserve a previously verified selection');
  assert.equal(node('usageSource').title, '', 'failed reads clear the old chat identity');
  assert.equal(node('projectValue').textContent, '未知');
  failAccount = true;
  await vm.runInContext('accountUsage()', context);
  assert.equal(node('weeklyValue').textContent, '未知（连接已断开）');
  assert.equal(node('fiveHourCard').hidden, true, 'known absence remains hidden while disconnected');
});
