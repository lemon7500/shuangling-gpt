import test from 'node:test';
import assert from 'node:assert/strict';
import vm from 'node:vm';
import { readFile } from 'node:fs/promises';
import { UsageReducer, formatUsageSummary } from '../../src/bridge/usage.mjs';

const at = Date.parse('2026-10-21T08:40:00Z');
const meta = id => ({ type: 'session_meta', payload: { id, thread_source: id === 'child' ? 'subagent' : 'user' } });
const event = (payload, timestamp = at) => ({ type: 'event_msg', timestamp: new Date(timestamp).toISOString(), payload: { type: 'token_count', ...payload } });
const info = { total_token_usage: { total_tokens: 19715162 }, last_token_usage: { input_tokens: 104519, cached_input_tokens: 104064, output_tokens: 241, total_tokens: 104760 }, model_context_window: 258400, private: 'PRIVATE BODY' };
const weekly = { used_percent: 7, window_minutes: 10080, resets_at: at / 1000 + 6 * 86400 };

test('usage verifies root and measures last request context without adding cumulative or cached tokens', () => {
  const r = new UsageReducer('root', { now: () => at });
  r.accept(event({ info })); assert.equal(r.snapshot().context.status, 'unknown');
  r.accept(meta('root'));
  r.accept(event({ info, thread_id: 'child' })); assert.equal(r.snapshot().context.status, 'unknown');
  r.accept(event({ info }));
  const c = r.snapshot().context;
  assert.equal(c.usedTokens, 104760);
  assert.equal(c.remainingTokens, 153640);
  assert.equal(c.windowTokens, 258400);
  assert.equal(c.usedPercent, 104760 * 100 / 258400);
  assert.ok(!JSON.stringify(r.snapshot()).includes('PRIVATE BODY'));
  assert.ok(!JSON.stringify(r.snapshot()).includes('19715162'));
  const child = new UsageReducer('child', { now: () => at });
  child.accept(meta('child')); child.accept(event({ info }));
  assert.equal(child.snapshot().context.status, 'unknown');
});

test('account windows use duration rather than primary order, absent 5h in a complete quota is inapplicable and credits are excluded', () => {
  const r = new UsageReducer('root', { now: () => at }); r.accept(meta('root'));
  r.accept(event({ rate_limits: { limit_id: 'codex', primary: weekly, secondary: { used_percent: 22.5, window_minutes: 300, resets_at: at / 1000 + 3600 }, credits: { balance: 'PRIVATE BALANCE' } } }));
  assert.equal(r.snapshot().account.weekly.remainingPercent, 93);
  assert.equal(r.snapshot().account.fiveHour.remainingPercent, 77.5);
  r.accept(event({ rate_limits: { limit_id: 'codex', primary: weekly, secondary: null } }));
  assert.equal(r.snapshot().account.fiveHour.status, 'not-applicable');
  assert.equal(r.snapshot().account.weekly.remainingPercent, 93);
  r.accept(event({ rate_limits: { limit_id: 'other-model', primary: { ...weekly, used_percent: 99 } } }));
  assert.equal(r.snapshot().account.weekly.remainingPercent, 93);
  const text = formatUsageSummary(r.snapshot());
  assert.doesNotMatch(text, /5 小时额度/);
  assert.match(text, /每周额度剩余：93%.*重置/);
  assert.ok(!JSON.stringify(r.snapshot()).includes('PRIVATE BALANCE'));
});

test('old context remains explicitly historical while expired account balances and invalid usage stay unknown', () => {
  let now = at;
  const r = new UsageReducer('root', { now: () => now }); r.accept(meta('root'));
  r.accept(event({ info, rate_limits: { primary: weekly, secondary: null } }));
  now += 6 * 60_000;
  assert.equal(r.snapshot().account.weekly.status, 'stale');
  assert.equal(r.snapshot().account.weekly.remainingPercent, undefined);
  assert.equal(r.snapshot().context.status, 'available');
  now += 10 * 60_000;
  assert.equal(r.snapshot().context.status, 'historical');
  assert.equal(r.snapshot().context.remainingTokens, 153640);
  assert.equal(r.snapshot().context.reason, 'sample-expired');
  assert.equal(r.snapshot().context.sample, 'last-model-request');
  assert.match(formatUsageSummary(r.snapshot()), /上次请求上下文剩余.*历史采样/);
  r.accept(event({ info: { ...info, last_token_usage: { total_tokens: 999999999 } } }, now));
  assert.equal(r.snapshot().context.status, 'unknown');
  r.accept(event({ info }, at)); // duplicated older record must not revive old data
  assert.equal(r.snapshot().context.status, 'unknown');
  r.accept(event({ rate_limits: { primary: { ...weekly, resets_at: Math.floor(now / 1000) - 1 } } }, now));
  assert.equal(r.snapshot().account.weekly.reason, 'reset-passed');
  r.unavailable('log-permission-denied');
  assert.equal(r.snapshot().context.reason, 'log-permission-denied');
  assert.equal(r.snapshot().account.weekly.remainingPercent, undefined);
  r.reset(); assert.equal(r.snapshot().context.status, 'unknown');
});

